CREATE SEQUENCE IF NOT EXISTS app_user_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE app_user
(
    id BIGINT NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id)
);

CREATE TABLE soldiers
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name                      VARCHAR(255),
    rank                      VARCHAR(255),
    phone                     VARCHAR(255),
    marital                   VARCHAR(255),
    housing                   VARCHAR(255),
    proficiency               VARCHAR(255),
    email                     VARCHAR(255),
    unit                      VARCHAR(255),
    soldier_id                BIGINT,
    role                      VARCHAR(255),
    mos                       VARCHAR(255),
    acft_date                 date,
    acft_score                INTEGER                                 NOT NULL,
    weapon_score              INTEGER                                 NOT NULL,
    weapon_qual_date          date,
    vision_due                date,
    pha_due                   date,
    dental_due                date,
    immunization_due          date,
    hearing_due               date,
    hiv_due                   date,
    profile_due               date,
    next_counseling_due       date,
    bio                       VARCHAR(255),
    blood_type                VARCHAR(255),
    is_married                BOOLEAN                                 NOT NULL,
    lives_on_post             BOOLEAN                                 NOT NULL,
    squad_leader              VARCHAR(255),
    squad_leader_phone_number VARCHAR(255),
    psg                       VARCHAR(255),
    psg_phone_number          VARCHAR(255),
    first_sgt                 VARCHAR(255),
    first_sgt_phone_number    VARCHAR(255),
    photo                     OID,
    CONSTRAINT pk_soldiers PRIMARY KEY (id)
);